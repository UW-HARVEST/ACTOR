#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# migrate_results_layout.sh — one-shot migration of the results/ submodule to
# the uniform per-case phase-dir layout.
#
#   OLD (four different shapes)                NEW (uniform)
#   Test-Corpus/<a>/<bat>/<case>/              <case>/
#     translated_rust_original/  (pre-verify)    translated/   (crate+result.json+logs)
#     translated_rust/           (post-verify)    verified/     (iff a verify ran)
#     result.json, logs/, summary.json@bat
#   Test-Corpus/kiro-translate/  (pseudo-agent, pre-verify snapshot of kiro)
#                                              -> folded into kiro/<case>/translated/, then DELETED
#   CRUST/<a>/<proj>/            (crate AT proj root)   <proj>/translated/  (crate+result.json+logs)
#   CRUST-blind/<a>/<proj>/translate/  + /verify/       <proj>/translated/  + /verified/
#   HarvestBench/<a>/<case>/translated_rust/            <case>/translated/
#
# Design rules (match tools/src, which reads the NEW layout):
#   * A Test-Corpus case's translated_rust/ is the POST-verify crate IFF that
#     case ran a verify phase. We detect "verify ran" by logs/verify.log at the
#     case root (only verify writes it; see verify.rs). If verify ran:
#         translated_rust_original/ -> translated/   (pre-verify crate)
#         translated_rust/          -> verified/      (post-verify crate)
#     else (translate-only, e.g. c2rust/laertes/kimi/oneshot/claude-*):
#         translated_rust/ (== _original) -> translated/   (no verified/)
#   * result.json (case root) describes the crate that was scored last:
#       -> verified/result.json if verified/ exists, else translated/result.json
#   * logs/{translation.log,verify.log} split into their phase dirs.
#   * summary.json (battery level, post-verify) stays as summary.json (headline).
#     A pre-verify summary is regenerated by `harvest-tools test` later, so we
#     don't fabricate summary_translated.json here.
#   * kiro-translate/ pseudo-agent: each case's translated_rust/ is a pre-verify
#     snapshot copied from kiro. Fold it into kiro/<case>/translated/ ONLY where
#     kiro doesn't already have a translated/ (kiro's own _original is the same
#     data). Then delete the kiro-translate/ agent dir entirely.
#
# SAFETY: idempotent (safe to re-run — skips cases already migrated), never
# deletes a crate without having copied it, and prints a summary. Runs inside
# the results/ submodule; commit there + bump the pointer in the superproject.
#
# Usage:
#   cd <ACTOR>/results        # the harvest-agentic-translate-results submodule
#   bash ../tools/migrate_results_layout.sh [--dry-run]
# ---------------------------------------------------------------------------
set -euo pipefail

DRY=0
[[ "${1:-}" == "--dry-run" ]] && DRY=1

say() { printf '%s\n' "$*"; }
run() { if [[ $DRY == 1 ]]; then say "  [dry-run] $*"; else eval "$*"; fi; }

# Move src -> dst (whole dir). Skip if dst already exists (idempotent).
move_dir() {
  local src="$1" dst="$2"
  [[ -d "$src" ]] || return 0
  [[ -e "$dst" ]] && { say "  skip (exists): $dst"; return 0; }
  run "mkdir -p \"$(dirname "$dst")\""
  run "mv \"$src\" \"$dst\""
}

# Ensure a logs/ file lands under a phase dir.
move_log() {
  local src="$1" phase_dir="$2" name="$3"
  [[ -f "$src" ]] || return 0
  run "mkdir -p \"$phase_dir/logs\""
  run "cp \"$src\" \"$phase_dir/logs/$name\""
}

migrate_test_corpus_case() {
  local case_dir="$1"
  local tr="$case_dir/translated_rust"
  local orig="$case_dir/translated_rust_original"
  local translated="$case_dir/translated"
  local verified="$case_dir/verified"

  # Already migrated?
  [[ -d "$translated" || -d "$verified" ]] && { say "  skip (migrated): $case_dir"; return 0; }
  [[ -d "$tr" || -d "$orig" ]] || return 0   # nothing to migrate

  # A case has a real POST-verify crate iff verify actually produced one. Two
  # signals, OR'd: (a) logs/verify.log present (the group's real case that ran
  # verify), or (b) translated_rust differs from translated_rust_original — this
  # catches shared-source config FOLLOWERS, which carry a propagated post-verify
  # translated_rust but have NO verify.log of their own. Translate-only agents
  # (c2rust/laertes/kimi/oneshot/…) have translated_rust == _original, so they
  # correctly fall through to the single-phase branch.
  local verify_ran=0
  if [[ -f "$case_dir/logs/verify.log" ]]; then
    verify_ran=1
  elif [[ -d "$orig" && -d "$tr" ]] && ! diff -rq "$orig" "$tr" >/dev/null 2>&1; then
    verify_ran=1
  fi

  if [[ $verify_ran == 1 && -d "$orig" ]]; then
    # Two-phase: _original is pre-verify, translated_rust is post-verify.
    move_dir "$orig" "$translated"
    move_dir "$tr"   "$verified"
    move_log "$case_dir/logs/translation.log" "$translated" "translation.log"
    move_log "$case_dir/logs/verify.log"      "$verified"   "verify.log"
    # result.json (last scored = post-verify) -> verified/
    [[ -f "$case_dir/result.json" ]] && run "cp \"$case_dir/result.json\" \"$verified/result.json\""
  else
    # Translate-only: the single crate is the pre-verify translated/.
    # Prefer _original if present (identical), else translated_rust.
    if [[ -d "$orig" ]]; then move_dir "$orig" "$translated"; run "rm -rf \"$tr\"";
    else move_dir "$tr" "$translated"; fi
    move_log "$case_dir/logs/translation.log" "$translated" "translation.log"
    [[ -f "$case_dir/result.json" ]] && run "cp \"$case_dir/result.json\" \"$translated/result.json\""
  fi
  # Clean up the old case-root leftovers (logs already copied into phase dirs).
  run "rm -rf \"$case_dir/translated_rust_original\" \"$case_dir/logs\" \"$case_dir/result.json\""
}

migrate_crust_regular_proj() {
  # CRUST-regular: the crate IS the project dir. Move everything except a
  # possibly-already-present translated/ into translated/.
  local proj="$1"
  local translated="$proj/translated"
  [[ -d "$translated" ]] && { say "  skip (migrated): $proj"; return 0; }
  [[ -f "$proj/Cargo.toml" ]] || return 0
  run "mkdir -p \"$translated\""
  # Move all entries of proj/ into translated/ (Cargo.toml, src/, c_src/, logs/,
  # result.json, translation.json, target/…). Use find to avoid globbing traps.
  run "find \"$proj\" -mindepth 1 -maxdepth 1 ! -name translated -exec mv {} \"$translated\"/ \\;"
}

migrate_crust_blind_proj() {
  local proj="$1"
  # translate/ -> translated/, verify/ -> verified/
  move_dir "$proj/translate" "$proj/translated"
  move_dir "$proj/verify"    "$proj/verified"
}

migrate_harvest_bench_case() {
  local case_dir="$1"
  move_dir "$case_dir/translated_rust" "$case_dir/translated"
  # result.json/logs at case root move into translated/ (single-phase).
  [[ -f "$case_dir/result.json" ]] && { run "mkdir -p \"$case_dir/translated\""; run "mv \"$case_dir/result.json\" \"$case_dir/translated/result.json\""; }
  [[ -d "$case_dir/logs" ]] && move_dir "$case_dir/logs" "$case_dir/translated/logs"
}

fold_kiro_translate() {
  # Fold the kiro-translate pseudo-agent's pre-verify snapshots into
  # kiro/<battery>/<case>/translated/ where kiro lacks one, then delete it.
  local kt="results/Test-Corpus/kiro-translate"
  local kiro="results/Test-Corpus/kiro"
  [[ -d "$kt" ]] || return 0
  say "Folding kiro-translate pseudo-agent into kiro/…/translated/"
  while IFS= read -r -d '' tr; do
    # tr = .../kiro-translate/<battery>/<case>/translated_rust
    local rel="${tr#"$kt"/}"                 # <battery>/<case>/translated_rust
    local case_rel="$(dirname "$rel")"       # <battery>/<case>
    local dst="$kiro/$case_rel/translated"
    if [[ -d "$dst" ]]; then
      say "  skip (kiro already has translated/): $case_rel"
    else
      move_dir "$tr" "$dst"
      move_log "$kt/$case_rel/logs/translation.log" "$dst" "translation.log"
    fi
    # The pseudo-agent's per-case result.json is the pre-verify score.
    local kt_rj="$kt/$case_rel/result.json"
    [[ -f "$kt_rj" && ! -f "$dst/result.json" ]] && { run "mkdir -p \"$dst\""; run "cp \"$kt_rj\" \"$dst/result.json\""; }
  done < <(find "$kt" -type d -name translated_rust -print0 2>/dev/null)
  # Battery-level: kiro-translate/<battery>/summary.json IS the pre-verify
  # (no-validate) battery summary. Land it as kiro/<battery>/summary_translated.json
  # so report.rs's no-validate derivation + invariant read the committed number
  # (no re-run needed).
  for bat in "$kt"/*/; do
    [[ -d "$bat" ]] || continue
    local bname; bname="$(basename "$bat")"
    local src="$bat/summary.json"
    local dst="$kiro/$bname/summary_translated.json"
    [[ -f "$src" && ! -f "$dst" ]] && { run "mkdir -p \"$kiro/$bname\""; run "cp \"$src\" \"$dst\""; }
  done
  run "rm -rf \"$kt\""
}

# ── main ────────────────────────────────────────────────────────────────
[[ -d results ]] || { echo "error: run from the ACTOR root (results/ submodule must be checked out)"; exit 1; }

say "== Test-Corpus (per-agent, per-battery, per-case) =="
for agent in results/Test-Corpus/*/; do
  [[ "$agent" == *"/kiro-translate/" ]] && continue   # handled by fold step
  for case_dir in "$agent"*/*/; do
    [[ -d "$case_dir" ]] && migrate_test_corpus_case "${case_dir%/}"
  done
done
fold_kiro_translate

say "== CRUST-regular =="
for proj in results/CRUST/*/*/; do
  [[ -d "$proj" ]] && migrate_crust_regular_proj "${proj%/}"
done

say "== CRUST-blind =="
for proj in results/CRUST-blind/*/*/; do
  [[ -d "$proj" ]] && migrate_crust_blind_proj "${proj%/}"
done

say "== HarvestBench =="
for case_dir in results/HarvestBench/*/*/; do
  [[ -d "$case_dir" ]] && migrate_harvest_bench_case "${case_dir%/}"
done

say ""
say "Migration complete. Next:"
say "  1. Verify:  harvest-tools report   (tables/*.tex must match committed numbers)"
say "  2. Verify:  harvest-tools --agent <a> test <dataset> --check   (per agent)"
say "     (the no-validate summary was migrated to kiro/<bat>/summary_translated.json"
say "      from the old kiro-translate pseudo-agent; no re-run needed)."
say "  3. Commit inside results/ submodule, then bump the pointer in ACTOR."
